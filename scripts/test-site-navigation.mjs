import assert from 'node:assert/strict';
import { readSiteRoute, invitationLink, chooseCircle, filterCircleMembers } from '../src/lib/siteNavigation.js';
const token = 'synthetic_invitation_12345';
assert.deepEqual(readSiteRoute(`#/join/${token}`), { stage:'circles', invite:token });
assert.deepEqual(readSiteRoute('#/circles'), { stage:'circles', invite:'' });
assert.equal(readSiteRoute('#/upload').stage, 'upload');
assert.equal(readSiteRoute('#/map').stage, 'map');
for (const hash of ['#/join/<script>', '#/join/short', '#/../../server', '#/report']) assert.deepEqual(readSiteRoute(hash), { stage:'entry', invite:'' });
const link = invitationLink(token, 'https://campus.example/app/?private=value#/circles');
const parsed = new URL(link);
assert.equal(parsed.origin, 'https://campus.example');
assert.equal(parsed.pathname, '/app/');
assert.equal(parsed.search, '');
assert.equal(parsed.hash, `#/join/${token}`);
assert.ok(!parsed.href.split('#')[0].includes(token), 'Invitation must not enter request URL or referrer.');
assert.throws(() => invitationLink('<script>', 'https://campus.example'));
assert.throws(() => invitationLink(token, 'javascript:alert(1)'));
assert.equal(chooseCircle([{id:'a'},{id:'b'}], 'b'), 'b');
assert.equal(chooseCircle([{id:'a'},{id:'b'}], 'removed'), 'a');
assert.equal(chooseCircle([], 'a'), null);
const members = [{id:'1',displayName:'测试同学',submission:{}},{id:'2',displayName:'ADMIN',submission:null},{id:'3',displayName:'未交同学',submission:null}];
assert.deepEqual(filterCircleMembers(members, '同学', 'submitted').map(m => m.id), ['1']);
assert.deepEqual(filterCircleMembers(members, ' admin ', 'pending').map(m => m.id), ['2']);
assert.equal(filterCircleMembers(members, '', 'all').length, 3);
assert.equal(filterCircleMembers(members, '不存在').length, 0);
assert.equal(members.length, 3, 'Filtering must not alter data used for full-circle export.');
console.log('页面恢复、邀请链接和成员筛选：全部通过');
