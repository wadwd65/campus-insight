/* ── 场地：一块石板地台（简洁，不抢建筑）────────────────────────────
   ★★★ v20 修正（实测发现）：v19 地面色 `0x8C8880` 渲染后明度 **225**，
     而建筑最高才 175（坡顶）⇒ **地面比建筑亮 50**，俯视时地台抢戏，
     建筑反而"陷进亮底里"。这是 Plan-A 被读作"灰板"的**外部因素之一**
     （不是建筑本身的问题，验证方式：同色建筑换暗地面后对比度立刻回来）。
   ✅ 修法：按 v17d 定色铁律反推 —— 朝上面受全照度抬升 ≈ +90，
      目标渲染 ≈185（比建筑亮一档但不抢）⇒ 材质 ≈ 185−90 = 95
      取 0x6E6C68（中性暖灰，明度 108），渲染后约 190。
      另外把地台尺寸略收，让画面重心回到建筑。

   ★★★ v21 再修（vivid.cjs 实测）：`0x6E6C68` 渲染成 **(180,181,180) sat=0.011**
     —— **纯灰，占 591,678 px（画面最大面）**。用户说"暗淡"，
     这个面就是最大的元凶（按 §16「面积最大的面决定观感」）。
     修法：给地面**暖砂岩色相**（R−B 拉开），并**压暗一档**
       （原来 180 比建筑墙 176 还亮 ⇒ 底色比主体亮，观感"发白发闷"）：
       0x6E6C68 → R110 G102 B 88  ⇒ R−B = 22（原来是 6）
       目标渲染 ≈ (168,158,142) sat ≈ 0.09，**仍低于建筑** ⇒ 不抢戏。
     ★ 地面**不做高饱和**（那是"脏"的来源，见技能 §16）—— 只要"不是纯灰"。

   ═══ ★★★ v21b：照"衰减比"反推，把第一版改太胆小的补回来 ═══
     ★★★ 对照实验 `exp-sat.cjs`（单变量逐灯开关，量全画面 sat）结论：
       baseline 0.0693 ／ 半球光关 0.0840(+21%) ／ 太阳+35% 0.0735(+6%)
       ／ fill 关 +3% ／ bounce 关 −1% ／ **outputEncoding→Linear 0.1301(+88%)**
     ⇒ **灯光不是主凶**（最好的单个因素也只 +21%，而且不能真关）。
       ⇒ 饱和度**只能从材质色本身拿**。这是"换口径"后的正确方向。

     ★ 实测「材质 sat → 渲染 sat」衰减比（三个面各不同，很关键）：
       墙   0.590 → 0.270   比 0.458
       地面 0.200 → 0.056   比 **0.280**  ← 朝上面被全照度稀释最狠
       坡面 0.177 → 0.070   比 0.395
     ⇒ 反推目标：**要渲染 sat 到 0.15 以上**：
       墙  需材质 sat ≥ 0.33（现在 0.59，够）
       地面需材质 sat ≥ **0.54**（现在 0.20 —— **差 2.7 倍**）
       坡面需材质 sat ≥ **0.38**（现在 0.18 —— **差 2.2 倍**） */
var GROUND_W = 108, GROUND_D = 54;
/* ★ v21b：0x6E6658(110,102,88) sat=0.20 → 0x8C6354(140,99,84) sat=0.40
   ★★★ v21c 回撤（**读图发现过头了**）：
     v21b 的 0x8C6354 渲染成 (197,176,167) sat=0.151 ——
     数字上"达标"，但**它占 591,678 px（画面最大面）**，
     读图后整块地台变成**粉橘色**，比建筑还抢眼，像"沙漠"。
     ⇒ 教训（★ 与技能 §16「面积最大的面决定观感」同构）：
        **同一个 sat 值，面积越大越"吵"** —— 大面必须比小面更灰。
       实测口径：地台 sat 应**低于建筑墙的 1/2**（墙 0.30 ⇒ 地面 ≤0.13）。
     修法：把 R 从 140 降回 122（减少"粉"），R−B 从 56 收到 40，
       目标渲染 sat ≈ 0.09（v20 是 0.011，v21d 取 0.09 —— 是 v20 的 8 倍，
       远远不是"纯灰"，但不再是粉橘）。 */
var mGround = mat(0x7A6350, { rough: 0.95 });
var ground = new THREE.Mesh(new THREE.PlaneGeometry(GROUND_W, GROUND_D), mGround);
ground.rotation.x = -Math.PI / 2;
ground.receiveShadow = true;
campus.add(ground);

/* ── 两栋公寓并排 ──────────────────────────────────────────────────
   ★ 同一相机、同一光照 ⇒ 单变量对照 */
var APT_W = 36, APT_D = 11.5;

var aptA = buildApartment(AC_A, {
  W: APT_W, D: APT_D, seed: 7,
  bays: 10,
  balcony: [0],                 /* 南面（+Z）做阳台 */
  core: [-13, 0],
  hipRoof: false,               /* ★ Plan-A：平顶（忠实实拍）*/
  name: '公寓A', nameDir: 0
});
aptA.position.set(0, 0, 9.0);
campus.add(aptA);

var aptB = buildApartment(AC_B, {
  W: APT_W, D: APT_D, seed: 7,
  bays: 10,
  balcony: [0],
  core: null,
  hipRoof: true,                /* ★ Plan-B：坡顶 */
  /* ★★★ v20：**不再传实验楼色板**。aptGableRoof 直接读 AC_B 里的
     roofSlopeA/B / fascia / ridgeCap / gableWall 等键 ⇒ 走"公寓暖灰
     石板瓦 + 双坡 + 老虎窗"，与实验楼的"冷蓝金属 + 四坡"彻底分家。 */
  roofAng:  Math.PI * 33 / 180, /* 33°（实验楼 27.5°）*/
  roofEave: 0.90,               /* 出檐 0.90m（实验楼 0.86m，同级）*/
  name: '公寓B', nameDir: 0
});
aptB.position.set(0, 0, -9.0);
campus.add(aptB);

/* ── 取景（排除大地台与装饰，只框住两栋楼）────────────────────────── */
scene.updateMatrixWorld(true);
fitCameraTo([aptA, aptB], 1.35, function (o) {
  if (o.userData && o.userData.noFrame) return false;
  if (o.isMesh && o.geometry) {
    var gt = o.geometry.type;
    if (gt === 'PlaneGeometry') {
      var p = o.geometry.parameters;
      if (p && p.width > 60) return false;
    }
    if (gt === 'RingGeometry') return false;
  }
  return true;
});

/* ── 交互：点击弹跳 ───────────────────────────────────────────────── */
var ray = new THREE.Raycaster(), ndc = new THREE.Vector2();
var picked = null;
var towers = [aptA, aptB];

renderer.domElement.addEventListener('pointerdown', function (e) {
  ndc.x = (e.clientX / W) * 2 - 1;
  ndc.y = -(e.clientY / H) * 2 + 1;
  ray.setFromCamera(ndc, camera);
  var hits = ray.intersectObjects(towers, true);
  if (!hits.length) return;
  var o = hits[0].object;
  while (o.parent && towers.indexOf(o) < 0) o = o.parent;
  if (towers.indexOf(o) < 0) return;
  if (o === picked) { o.position.y = 0; picked = null; return; }
  if (picked) picked.position.y = 0;
  picked = o;
});

/* ── 渲染循环 ─────────────────────────────────────────────────────── */
function loop() {
  requestAnimationFrame(loop);
  renderer.render(scene, camera);
}
loop();

