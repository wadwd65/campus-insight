/* ══════════════════════════════════════════════════════════════════════
   ★★★ 关键：AC 是**全局可变色板**，makeApartment 读它。
   用 buildApartment(colorSet, opt) 包一层：切换色板 → 建楼 → 还原。
   ══════════════════════════════════════════════════════════════════════ */
function buildApartment(colorSet, opt) {
  var saved = {};
  for (var k in AC) saved[k] = AC[k];
  for (var k2 in colorSet) AC[k2] = colorSet[k2];
  var g = makeApartment(opt.W, opt.D, opt);
  for (var k3 in saved) AC[k3] = saved[k3];
  return g;
}

