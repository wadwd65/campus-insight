/**
 * 内容层的「终端化」形式语言（浅色版）。
 *
 * 为什么需要这一份：
 *   V3 之前，这个作品有两种互不相干的样子 ——
 *   入场/地图是深色终端（有网格、切角、等宽字、编号），
 *   欢迎页/问卷/报告是浅色数据页（白卡片、圆角、系统字体）。
 *   两边的观感差得太远，翻页的时候不像同一个作品翻到了下一页，
 *   像从"一个游戏"跳到了"一个后台管理系统"。
 *
 * 这一份要解决的就是那件事：**把形式语言抽出来，而不是把底色统一**。
 *
 * 为什么不是「干脆全站深色」：
 *   报告页有一张雷达图、一张环形图、一条折线图，外加两段正文。
 *   深色底会把它们全部推倒重做（ECharts 主题、对比度、打印友好度），
 *   而这几页是已经跑通、已经录过验证的。代价与收益不成比例。
 *   更实际的理由：**读长文本时浅色底更舒服**，报告是要被读完的。
 *
 * 所以边界是这样：
 *   底色沿 content 那套（仍是浅色），只把**形式**换成终端的 ——
 *   切角、等宽小标、章节编号、细描边、无圆角或极小圆角。
 *
 * 与 terminalTheme.js 的分工：
 *   terminalTheme.js 管**深色场景**（背景 / 面板 / 强调色）。
 *   这一份管**浅色内容区**的形式常量，只放"怎么画"，不放"画什么色"。
 *   色值仍走 index.css 的 CSS 变量，免得 ECharts 之外的色又被复制一份。
 */

/**
 * 切角面板的内联样式（浅色版）。
 *
 * 和深色版 `.term-panel` 用**同一个几何**（切角、对角两处），
 * 这是刻意的：形状一致，人一眼就知道"这两块是同一套东西"，哪怕底色不同。
 *
 * ⚠️ 切角**尺寸随面板宽度走**，不能是一个常数。
 *    14px 放在入场那个小按钮上很清楚，但放在一张 900px 宽的卡片上，
 *    两个角各缺 14px 就完全看不出来 —— 而"看不出来"比"没有"更糟：
 *    它只会在视觉上留下一点说不清的别扭感，像是渲染出错。
 *    这里给两档（窄面板 / 宽面板），由 TermPanel 按实际用途选。
 */
export const CUT_SIZE = 14;
export const CUT_SIZE_WIDE = 22;

/**
 * 等宽小标 —— 内容区的 `// 你的报告` 那种行。
 *
 * 这类小标在入场里到处都是，是"终端感"最省力的载体：
 * 它不改变任何布局，只是把一行字换成等宽 + 拉字距，
 * 整块区域的观感就从"网页"变成"仪表盘的标签"。
 */
export function monoTag(extra = {}) {
  return {
    fontFamily: 'ui-monospace, "SFMono-Regular", "Cascadia Mono", Consolas, monospace',
    letterSpacing: '0.14em',
    fontSize: 11,
    ...extra,
  };
}

/**
 * 章节编号。
 *
 * 报告页原先的标题是裸的「大学生活者画像」。
 * 加一个 01/02/03 的编号，作用不是装饰 ——
 * 它让"这份报告有五块、你现在看到第几块"这件事在滚动时始终成立，
 * 而报告页本来就设计了四拍依次出现（见 ReportView.jsx）。
 * 编号是那个"依次"在视觉上的锚点。
 */
export function sectionIndex(n) {
  return String(n).padStart(2, '0');
}

/**
 * 浅色内容区的描边色。
 * 单独导出，是为了「细描边」这个决定只有一个入口 ——
 * 想整体调深调浅时改这里，而不是满文件找 border-[var(--line)]。
 */
export const HAIRLINE = '1px solid var(--line)';

/**
 * 报告页与欢迎页共用的两个强调色 —— 取自入场立绘的那套（青 / 琥珀）。
 *
 * 为什么不用 theme.js 的 BRAND（#4f46e5 靛紫）：
 *   BRAND 是"链接与主按钮"的颜色，它服务的是"这里可以点"。
 *   而这里要的是"这是终端在说话"，属于氛围，两者混用会让按钮失去辨识度。
 *   入场的立绘就是青（偏学术）与琥珀（偏运动）两色 ——
 *   内容区沿用同一对色，四页之间的血缘才是真的。
 */
export const TERM_INK = {
  cyan: '#4fa8d8',
  amber: '#f5a623',
};
