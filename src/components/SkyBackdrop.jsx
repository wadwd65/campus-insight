/**
 * SkyBackdrop —— 答题页的天空背景（2026-10-14 v6）
 *
 * 用户原话：「做一个天空的背景，在答题页面，让……拥有天空的颜色也是要有一点的，
 * 做一个微动态，这样防止消耗太多资源」。
 *
 * ── 三个约束，逐条对应到实现 ────────────────────────────────────
 *
 * ① **要有天空的颜色，但不能抢内容。**
 *    这是一条很窄的路：太淡 = 等于没有（就是之前的"太素"）；太浓 = 文字读不清。
 *    办法是**把色彩压在明度高的区间**（L 都在 0.85 以上），只让**色相**变化：
 *    顶部淡天蓝 → 中部青白 → 近地暖沙。眼睛读到的是"一片天"，
 *    但任何一处的亮度都还在浅底区间，正文那套深色文字不用改一个色号。
 *    这一条是刻意的取舍：如果做成黄昏深蓝（更好看），
 *    整页文字就得反白，图表也要重做主题 —— 代价不成比例。
 *
 * ② **微动态，省资源。**
 *    只动 `transform`，不动任何会触发重绘/重排的属性（不用 background-position、
 *    不用 filter、不用 opacity 的连续变化）。
 *    三层云各自 110~170 秒横向漂 4%，走 GPU 合成，且 `alternate` 让它来回而非重置 —— 
 *    这个项目有过"多层实时模糊 + 持续动画 → 帧数狂掉"的教训（见 index.css 的 .atmo-panel），
 *    所以这里的动画预算给得很紧：**只有 transform，且极慢**。
 *    `prefers-reduced-motion` 下全部静止（站点已有全局降级规则）。
 *
 * ③ **紫色少一点。**
 *    用户明确说不想看到太多紫色。所以天空三段里**一段紫都没有**：
 *    蓝 → 青 → 暖沙。这也是整站主色从蓝紫改靛蓝的同一件事在背景上的延续。
 *
 * 为什么不用绘世出一张天空图：天空需要**无缝铺满任意视口**（1440×900 / 390×844 / …），
 * 一张位图做不到，多张拼又会露接缝。渐变色带天生无缝、体积为零、还能自由调色相 ——
 * 这一处"程序化"比"生成图"更合适。
 */

import { memo } from 'react';

function SkyBackdrop() {
  return (
    <div className="sky-backdrop" aria-hidden="true">
      {/* ① 兜底渐变（图挂了也有底）*/}
      <div className="sky-base" />

      {/* ② 真天空照片（绘世出的 sky.webp，7.4KB）。
             它自带 170 秒的极缓漂移 —— 这就是"微动态"的全部开销：
             一个 transform 动画，走 GPU 合成，零重绘。 */}
      <div className="sky-photo" />

      {/* ③ 云影：两团极淡的白色柔边，给照片再叠一层慢速"云在走" */}
      <div className="sky-clouds sky-clouds-a" />
      <div className="sky-clouds sky-clouds-b" />

      {/* ④ 光幕：天空从上往下渐隐进内容区，给正文让出可读性。
             它是 10-15 新增的 —— 把"天空够艳"和"文字够清楚"拆成两个参数。 */}
      <div className="sky-scrim" />

      {/* ⑤ 近地暖光：一片极淡的琥珀，暗示"天快亮了"。
             它压在页面底部，正好托住选项卡片那一带 */}
      <div className="sky-glow" />
    </div>
  );
}

export default memo(SkyBackdrop);
